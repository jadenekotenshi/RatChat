/* rfc8439_*: RFC 8439 SS2.8.2's published ChaCha20-Poly1305 test vector, computed here via real
 * OpenSSL (EVP_chacha20_poly1305) rather than hand-transcribed from the RFC text, to rule out a
 * transcription error either way -- the ciphertext/tag OpenSSL produced are the RFC's own
 * published values. Tests the raw AEAD construction, no TLS framing involved.
 *
 * gcm_* and cc_*: two real TLS 1.2 records each (client and server direction, different keys), from
 * real local `openssl s_server`/`s_client` handshakes -- PSK-AES128-GCM-SHA256 and
 * PSK-CHACHA20-POLY1305, `-no_ems` (see tls_prf_vectors.h for why). Captured via a small raw TCP
 * relay/logger sitting between client and server (not `-msg`, which only ever shows OpenSSL's
 * own already-decrypted view of a message, never the real wire ciphertext); key material
 * derived with ratchat's own already-verified tls_prf(); the plaintext each decrypts to is the
 * real Finished message, cross-checked against OpenSSL's own `-msg` trace of the same session.
 * Every one of these four records was independently decrypted and tag-verified by linking
 * against real OpenSSL (EVP_aes_128_gcm / EVP_chacha20_poly1305) before being trusted here --
 * this is checking core/tls_aead_gcm.c and core/tls_aead_chacha.c against OpenSSL's own
 * implementation, not against numbers this project invented.
 *
 * The GCM explicit nonce is a real wart worth documenting: RFC 5246 leaves the 8-byte explicit
 * nonce's value up to the implementation, and ratchat's own tls_gcm_seal/open (ratchat's own
 * design choice, ratchat's own future writes) use the record's true sequence number for it. This
 * OpenSSL build's real captured explicit nonce (gcm_*_seq below) is NOT the true sequence number
 * (which is 0 for both these first-record Finished messages, and IS what's embedded in
 * gcm_*_aad's own first 8 bytes) -- it's some other value OpenSSL chose instead, equally
 * RFC-legal. tls_gcm_seal/open's own `seq` parameter only ever controls the nonce, never the
 * AAD (the caller supplies that separately), so this still exercises the real code path
 * correctly: pass gcm_*_seq as `seq` (to reproduce OpenSSL's actual nonce) and gcm_*_aad as-is
 * (which carries the real seq_num=0 OpenSSL actually authenticated over). ChaCha20-Poly1305 has
 * no separate wire-visible explicit nonce at all (RFC 7905), so no such split exists there --
 * cc_*_iv XORed with the plain true sequence number (0) is the whole nonce. */

