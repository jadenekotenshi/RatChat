/* Real vectors from a local TLS 1.2 handshake: `openssl s_server -nocert -psk <hex> -cipher
 * PSK-AES128-GCM-SHA256 -tls1_2 -no_ems -accept ...` against `openssl s_client` with the same
 * PSK/cipher, `-msg -keylogfile client.keylog`. `-no_ems` matters: extended_master_secret
 * (RFC 7627) is on by default in a modern OpenSSL and replaces the classic
 * client_random||server_random seed with a session-hash seed -- this project's TLS 1.2 doesn't
 * implement RFC 7627, so the vector needs it off to exercise the plain RFC 5246 SS8.1 path.
 *
 * client_random/server_random are read out of the ClientHello/ServerHello bytes in the `-msg`
 * trace; master_secret is the real one OpenSSL derived, read from the keylog file. For a plain
 * PSK cipher suite (no DH/RSA component) RFC 4279 SS2 defines the premaster secret as
 * uint16(N) || zeros(N) || uint16(N) || psk, N = the PSK length -- for the 16-byte PSK below,
 * premaster_secret = 0010 0000000000000000000000000000000000 10 <psk>. This was independently
 * confirmed (once -no_ems was found to be the missing piece) against openssl's own `openssl kdf
 * ... TLS1-PRF` command before ratchat's own tls_prf() was tested against it.
 *
 * key_block40/key_block70 are NOT from real derived TLS record keys (this project has no AEAD
 * implementation yet to decrypt a real record with them -- that cross-check belongs to a later
 * phase); they are the "key expansion" label applied to the same real master_secret/randoms
 * above. Originally generated via `openssl kdf ... TLS1-PRF`, but that CLI invocation turned out
 * not to reproduce even the already-verified master_secret above when tried against it directly
 * -- some misunderstanding of that tool's own parameters, never tracked down -- so it was
 * discarded as unreliable rather than trusted. These two vectors are instead a second, genuinely
 * independent implementation: Python's stdlib `hmac`/`hashlib`, composing RFC 5246 SS5's P_hash
 * from scratch the same way core/tls_prf.c does, checked directly against the real captured
 * master_secret/randoms above (not against openssl's kdf tool). key_block70 is the same
 * derivation asked for 30 more bytes, and is a strict extension of key_block40 -- confirming
 * P_hash's own incremental-output property against that second implementation too. */

